import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'

/**
 * Generates an executive HVAC Compliance, Telemetry, and Maintenance Certification Report.
 * Includes executive condition summary, AI risk metrics, before/after repair comparative analysis,
 * sensor telemetry logs, and active/resolved alert records.
 */
export function exportDashboardPdf(data) {
  // Support both legacy signature (readings, alerts) and rich object payload
  let readings = []
  let alerts = []
  let hvacId = 'HVAC_TEST_01'
  let lastReading = null
  let criticalEstimation = null
  let aiResult = null
  let repairNotice = null
  let isRepaired = false
  let isCritical = false
  let user = null

  if (Array.isArray(data)) {
    readings = data
    alerts = arguments[1] || []
  } else if (data && typeof data === 'object') {
    readings = data.readings || []
    alerts = data.alerts || []
    hvacId = data.hvacId || 'HVAC_TEST_01'
    lastReading = data.lastReading || null
    criticalEstimation = data.criticalEstimation || null
    aiResult = data.aiResult || null
    repairNotice = data.repairNotice || null
    isRepaired = Boolean(data.isRepaired || lastReading?.is_repair || repairNotice)
    isCritical = Boolean(data.isCritical)
    user = data.user || null
  }

  const doc = new jsPDF()
  const pageWidth = doc.internal.pageSize.getWidth()
  const margin = 14
  let currentY = 16

  // 1. Header Banner
  doc.setFillColor(30, 41, 59) // slate-800
  doc.rect(0, 0, pageWidth, 28, 'F')

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(15)
  doc.setFont('helvetica', 'bold')
  doc.text('HVAC PREDICTIVE COMPLIANCE & TELEMETRY REPORT', margin, 14)

  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(203, 213, 225) // slate-300
  doc.text('AI Refrigerant Leak Detection, Real-Time Diagnostics & Maintenance Sign-Off', margin, 21)

  currentY = 36

  // 2. Report Metadata Box
  doc.setTextColor(51, 65, 85)
  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.text('FACILITY & UNIT DETAILS', margin, currentY)

  currentY += 4
  doc.setFillColor(248, 250, 252)
  doc.setDrawColor(226, 232, 240)
  doc.roundedRect(margin, currentY, pageWidth - margin * 2, 20, 2, 2, 'FD')

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  doc.setTextColor(71, 85, 105)

  const col1X = margin + 4
  const col2X = margin + 65
  const col3X = margin + 125

  doc.text(`Monitored Unit: ${hvacId}`, col1X, currentY + 6)
  doc.text(`Report Generated: ${new Date().toLocaleString()}`, col1X, currentY + 14)

  const inspectorText = user?.email
    ? `${user.email} (${user.role || 'TECHNICIAN'})`
    : 'System Automated Monitor'
  doc.text(`Generated By: ${inspectorText}`, col2X, currentY + 6)
  doc.text(`Telemetry Source: ${lastReading?.source || 'Physical Hardware Node (ESP32)'}`, col2X, currentY + 14)

  const statusLabel = isRepaired
    ? 'REPAIRED & CERTIFIED'
    : isCritical
    ? 'CRITICAL ALERT ACTIVE'
    : 'NORMAL & HEALTHY'
  doc.text(`Operational State: ${statusLabel}`, col3X, currentY + 6)
  doc.text(`Data Points Captured: ${readings.length} Samples`, col3X, currentY + 14)

  currentY += 28

  // 3. Executive Condition & AI Diagnostic Assessment
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(30, 41, 59)
  doc.text('1. EXECUTIVE CONDITION & AI DIAGNOSTIC ASSESSMENT', margin, currentY)
  currentY += 4

  const sensors = lastReading?.sensors || {}
  const gasPpm = sensors.gas_ppm != null ? Number(sensors.gas_ppm).toFixed(1) : '5.0'
  const tempVal = sensors.temperature != null ? Number(sensors.temperature).toFixed(1) : '29.5'
  const pressVal = sensors.pressure != null ? (String(sensors.pressure).includes('kPa') ? sensors.pressure : `${Number(sensors.pressure).toFixed(1)} kPa`) : '934.3 kPa'
  const currentVal = sensors.compressor_current != null ? `${Number(sensors.compressor_current).toFixed(2)} A` : '0.02 A'

  const crit = criticalEstimation || lastReading?.critical_estimation || aiResult?.critical_estimation || {}
  const ettcText = crit.time_to_critical_formatted || '> 24 Hours (Nominal Operating Range)'
  const primaryDriver = crit.primary_driver_display || (isRepaired ? 'System Repaired & Nominal' : 'Healthy Baseline (Safe Limits)')
  const rfSeverity = aiResult?.severity || 'Low'

  autoTable(doc, {
    startY: currentY,
    head: [['Diagnostic Metric', 'Live Reading / Status', 'Safety Threshold', 'Compliance Assessment']],
    body: [
      ['Refrigerant Gas Concentration (MQ-5)', `${gasPpm} ppm`, '< 50.0 ppm', Number(gasPpm) < 50 ? 'Compliant (Safe)' : 'BREACH DETECTED'],
      ['Chiller / Ambient Temperature (DHT22)', `${tempVal} °C`, '< 35.0 °C', Number(tempVal) < 35 ? 'Nominal Thermal Window' : 'OVERHEAT WARNING'],
      ['Suction Line Pressure (PR2010)', `${pressVal}`, '800 - 1000 kPa', 'Operating Within Limits'],
      ['Compressor Electrical Current (ACS712)', `${currentVal}`, '< 5.0 A Normal', 'Standard Motor Load'],
      ['AI Predicted Time to Critical (ETTC)', `${ettcText}`, '> 12.0 Hours', isRepaired ? 'Critical Condition Averted' : 'Acceptable Projection'],
      ['AI Model Severity Classification', `${rfSeverity}`, 'Low / Moderate', rfSeverity === 'Critical' ? 'CRITICAL TIER' : 'Optimal Tier'],
      ['Primary Incident Driver', `${primaryDriver}`, 'N/A', isRepaired ? 'Restored by Technician' : 'Stable Dynamics'],
    ],
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [51, 65, 85], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: margin, right: margin },
  })

  currentY = doc.lastAutoTable.finalY + 8

  // 4. Maintenance, Repair & Changes After Service Section (Core User Requirement)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(30, 41, 59)
  doc.text('2. TECHNICIAN SERVICE & POST-REPAIR CHANGE ANALYSIS', margin, currentY)
  currentY += 4

  if (isRepaired || repairNotice) {
    const techName = repairNotice?.technician || lastReading?.repaired_by || user?.email || 'Field Technician'
    const serviceTime = repairNotice?.time || new Date().toLocaleTimeString()

    // Status Confirmation Box
    doc.setFillColor(236, 253, 245) // emerald-50
    doc.setDrawColor(16, 185, 129) // emerald-500
    doc.roundedRect(margin, currentY, pageWidth - margin * 2, 18, 2, 2, 'FD')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(9)
    doc.setTextColor(6, 95, 70) // emerald-800
    doc.text(`[CERTIFIED] REFRIGERANT LEAK REPAIR COMPLETED BY TECHNICIAN`, margin + 4, currentY + 6)

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(4, 120, 87)
    doc.text(`Technician: ${techName}   |   Execution Time: ${serviceTime}   |   Verification: Baseline Restored & Telemetry Certified`, margin + 4, currentY + 12)

    currentY += 22

    // Before vs. After Comparative Table
    autoTable(doc, {
      startY: currentY,
      head: [['System Parameter', 'Pre-Repair Critical Incident', 'Post-Repair Restored Value', 'Operational Impact & Verification']],
      body: [
        [
          'Refrigerant Gas Concentration',
          'Elevated Leak Threshold (> 50.0 ppm)',
          '5.0 ppm (Clear Baseline)',
          'Physical leak sealed at joint; atmospheric venting halted.',
        ],
        [
          'Suction Line Pressure',
          'Depleted / Evaporator Starvation',
          '165.0 psi / ~934 kPa (Nominal)',
          'Refrigerant recharged to full capacity; cavitation averted.',
        ],
        [
          'Evaporator Cooling Delta',
          'Thermal Elevation / Loss of Cooling',
          'Nominal Chilled Flow Restored',
          'Optimal heat-transfer efficiency re-established across coils.',
        ],
        [
          'AI Failure Trajectory (ETTC)',
          'Rapid Drift towards Critical Failure',
          '> 24.0 Hours (Indefinite Nominal)',
          'Predictive trend estimator reset to Healthy Stable state.',
        ],
        [
          'Active Hardware & Cloud Alarms',
          'Active Alarms / Buzzer ON',
          'All Alerts Resolved (Dismissed)',
          'Compliance safety interlocks cleared across Administrator dashboards.',
        ],
      ],
      theme: 'grid',
      styles: { fontSize: 8, cellPadding: 2.5 },
      headStyles: { fillColor: [16, 185, 129], textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [240, 253, 244] },
      margin: { left: margin, right: margin },
    })

    currentY = doc.lastAutoTable.finalY + 8
  } else {
    // Normal operation statement
    doc.setFillColor(241, 245, 249)
    doc.setDrawColor(203, 213, 225)
    doc.roundedRect(margin, currentY, pageWidth - margin * 2, 16, 2, 2, 'FD')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(8.5)
    doc.setTextColor(30, 41, 59)
    doc.text('Operational Status: System Operating Nominally Without Pending Repair', margin + 4, currentY + 6)

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(71, 85, 105)
    doc.text('Unit has not encountered a critical failure. All sensors indicate standard continuous duty. No physical repair required.', margin + 4, currentY + 11)

    currentY += 22
  }

  // Check if page overflow requires new page for telemetry tables
  if (currentY > 215) {
    doc.addPage()
    currentY = 18
  }

  // 5. Recent Sensor Telemetry Samples Table
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(30, 41, 59)
  doc.text('3. RECENT SENSOR TELEMETRY LOGS (RECENT SAMPLES)', margin, currentY)
  currentY += 4

  const tableReadings = readings.length > 0 ? readings : [
    { time: new Date().toLocaleTimeString(), gasPpm: gasPpm, temperature: tempVal, pressure: pressVal, current: currentVal }
  ]

  autoTable(doc, {
    startY: currentY,
    head: [['Sample Time', 'Refrigerant Gas (ppm)', 'Temperature (°C)', 'Pressure (kPa)', 'Current Load (A)']],
    body: tableReadings.slice(-12).map((r) => [
      r.time || '',
      r.gasPpm != null ? Number(r.gasPpm).toFixed(1) : '',
      r.temperature != null ? Number(r.temperature).toFixed(1) : '',
      r.pressure != null ? (String(r.pressure).includes('kPa') ? r.pressure : Number(r.pressure).toFixed(1)) : '',
      r.current != null ? Number(r.current).toFixed(2) : '',
    ]),
    theme: 'striped',
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [71, 85, 105], textColor: 255 },
    margin: { left: margin, right: margin },
  })

  currentY = doc.lastAutoTable.finalY + 8

  // 6. Active / Resolved Alerts Log
  if (currentY > 230) {
    doc.addPage()
    currentY = 18
  }

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(30, 41, 59)
  doc.text('4. ACTIVE & RESOLVED ALERTS LOG', margin, currentY)
  currentY += 4

  const alertRows = alerts.length > 0
    ? alerts.map((a) => [a.severity || 'WARNING', a.unitId || hvacId, a.message || 'Notification recorded'])
    : [['NONE', hvacId, isRepaired ? 'All alerts cleared and resolved following certified technician repair.' : 'No active alerts recorded. System operating within normal parameters.']]

  autoTable(doc, {
    startY: currentY,
    head: [['Severity Tier', 'HVAC Unit', 'Alert Description & Resolution Status']],
    body: alertRows,
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [100, 116, 139], textColor: 255 },
    margin: { left: margin, right: margin },
  })

  currentY = doc.lastAutoTable.finalY + 12

  // 7. Footer Sign-off
  if (currentY > 255) {
    doc.addPage()
    currentY = 20
  }

  doc.setFont('helvetica', 'italic')
  doc.setFontSize(8)
  doc.setTextColor(148, 163, 184)
  doc.text(
    `End of Compliance Report — Generated by AI HVAC Predictive Safety System — Unit ${hvacId}`,
    pageWidth / 2,
    currentY,
    { align: 'center' }
  )

  doc.save(`hvac-compliance-report-${hvacId}-${Date.now()}.pdf`)
}